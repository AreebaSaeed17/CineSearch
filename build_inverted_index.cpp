#include <iostream>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>
using namespace std;

// this represents each sighting of a word and makes an entry
struct Posting {
    int docId;
    int frequency;
    int inTitle;
};

/*
takes the file generated by forwardindex as an input
each line of the forward_index.txt is one post and its word info
processes post by post

Since documents were read in increasing docId order so every word's list is already sorted by docId
*/
int main() {
    // READING FROM THE FILE
    // verify and read file
    ifstream forwardFile("forward_index.txt");
    if (!forwardFile.is_open()) {
        cout << "forward_index.txt not found. Run build_forward first." << endl;
        return 1;
    }

    // postingsOfWord[wordId] = list of documents that contain that word
    vector<vector<Posting>> postingsOfWord;

    // read the first number on the line; which is the document's ID
    string line;
    while (getline(forwardFile, line)) {
        istringstream lineStream(line);
        int docId;
        lineStream >> docId;
 
        // take each {wordId:frequency:inTitle} from a post(line) one by one
        // split each chunk apart at the colons (:) 
            // store the three numbers into separate variables wordId, frequency, inTitle
        string token;
        while (lineStream >> token) {
            int wordId, frequency, inTitle;
            sscanf(token.c_str(), "%d:%d:%d", &wordId, &frequency, &inTitle);

            // when it encouters a new wordid from the file thast hasnt been added to the list yet,
            // it will increase the size of that list and add it at the end of the last along with its info
            if (wordId >= (int)postingsOfWord.size()) postingsOfWord.resize(wordId + 1);
            postingsOfWord[wordId].push_back({docId, frequency, inTitle});
        }
    }

    // WRITING TO THE FILE
    // How many total documents contain that word (postings.size()) are stored along with it
        // this tells how common or rare a certian word is
    // Every docId:frequency: inTitle for that wordid is stored alongside
 
    ofstream invertedFile("inverted_index.txt");
    for (int wordId = 0; wordId < (int)postingsOfWord.size(); wordId++) {
        const vector<Posting>& postings = postingsOfWord[wordId];
        if (postings.empty()) continue;

        invertedFile << wordId << " " << postings.size();
        for (const Posting& p : postings) {
            invertedFile << " " << p.docId << ":" << p.frequency << ":" << p.inTitle;
        }
        invertedFile << "\n";
    }

    cout << "Done. Words in inverted index: " << postingsOfWord.size() << endl;
    return 0;
}
